#!/usr/bin/env bun
/**
 * Regenerates the `BINARY_EXTENSIONS_SET` block inside `src/utils.ts` from the
 * `binary-extensions` package.
 *
 * `binary-extensions` is a dev dependency: the extension list is inlined into the
 * library source, so the published bundle carries no runtime dependency on the
 * package, and the list stays available as a literal union of extensions.
 *
 * Run this after bumping `binary-extensions`:
 *   bun run scripts/generate-binary-extensions.ts
 */

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const UTILS_FILE = path.join(import.meta.dir, '..', 'src', 'utils.ts')

/**
 * Markers delimiting the generated block. Move them around `src/utils.ts` to
 * relocate the block — the script rewrites whatever sits between them, and
 * appends the block at the end of the file when the markers are missing.
 */
const START_MARKER = '// <binary-extensions>'
const END_MARKER = '// </binary-extensions>'

const extensions = readExtensions()

const block = [
  `${START_MARKER} — generated by scripts/generate-binary-extensions.ts, do not edit`,
  'export const BINARY_EXTENSIONS_SET = new Set([',
  ...extensions.map((extension) => `  '${extension}',`),
  '] as const)',
  '',
  'export type BinaryExtension = SetType<typeof BINARY_EXTENSIONS_SET>',
  END_MARKER,
].join('\n')

const source = readFileSync(UTILS_FILE, 'utf-8')

const start = source.indexOf(START_MARKER)
const end = start === -1 ? -1 : source.indexOf(END_MARKER, start)

const updated = start !== -1 && end !== -1
  ? source.slice(0, start) + block + source.slice(end + END_MARKER.length)
  : `${source.trimEnd()}\n\n${block}\n`

writeFileSync(UTILS_FILE, updated)

console.log(`Updated ${extensions.length} binary extensions in ${path.relative(process.cwd(), UTILS_FILE)}`)

function readExtensions(): string[] {
  const packageEntry = Bun.resolveSync('binary-extensions', path.join(import.meta.dir, '..'))
  const listFile = path.join(path.dirname(packageEntry), 'binary-extensions.json')
  return JSON.parse(readFileSync(listFile, 'utf-8')) as string[]
}
